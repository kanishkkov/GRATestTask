
from pathlib import Path
import faiss
import pymupdf  # PyMuPDF
from sentence_transformers import SentenceTransformer


MODEL_NAME = "all-MiniLM-L6-v2"
# Covers, letters, contents, promotional/contact pages, blank notes, and back covers.
EXCLUDED_PAGES = {
    "llc.pdf": {1, 2, 3, 4, 18, 20},
    "sole_proprietorship.pdf": {1, 2, 3, 4, 10, 12, 13, 14, 16},
}
model = None
index = None
indexed_chunks = []

## Function to load documents from a specified directory and extract text from each page of PDF files.
def load_documents(directory="documents"):
    pages = []

    for pdf_path in sorted(Path(directory).glob("*.pdf")):
        doc = pymupdf.open(pdf_path)

        for page_num, page in enumerate(doc, start=1):
            text = page.get_text().strip()

            if text:
                pages.append({
                    "source": pdf_path.name,
                    "page": page_num,
                    "text": text
                })

        doc.close()

    return pages

#Function to chunk the extracted text from each page into smaller segments based on specified chunk size and overlap.
def chunk_documents(pages, chunk_size=800, overlap=150):
    chunks = []

    for page in pages:
        text = " ".join(page["text"].split())

        start = 0
        while start < len(text):
            end = min(start + chunk_size, len(text))

            chunks.append({
                "source": page["source"],
                "page": page["page"],
                "text": text[start:end]
            })

            if end == len(text):
                break

            start = end - overlap

    return chunks

#This function builds an in-memory index of the text chunks using embeddings generated by a pre-trained SentenceTransformer model. It raises an error if no chunks are provided.
def build_index(chunks):
    """Embed chunks and store them in an in-memory cosine-similarity index."""
    global model, index, indexed_chunks

    chunks_to_index = [
        chunk for chunk in chunks
        if chunk["page"] not in EXCLUDED_PAGES.get(chunk["source"], set())
    ]

    if not chunks_to_index:
        raise ValueError("Cannot build an index without chunks")

    model = SentenceTransformer(MODEL_NAME)
    embeddings = model.encode(
        [chunk["text"] for chunk in chunks_to_index],
        normalize_embeddings=True,
        convert_to_numpy=True,
    ).astype("float32")

    index = faiss.IndexFlatIP(embeddings.shape[1])
    index.add(embeddings)
    indexed_chunks = chunks_to_index


def retrieve(question, k=6):
    """Return the chunks most semantically similar to a question."""
    if model is None or index is None:
        raise RuntimeError("Call build_index(chunks) before retrieve()")
    if k < 1:
        return []

    question_embedding = model.encode(
        [question],
        normalize_embeddings=True,
        convert_to_numpy=True,
    ).astype("float32")
    scores, positions = index.search(question_embedding, min(k, index.ntotal))

    results = []
    for score, position in zip(scores[0], positions[0]):
        chunk = indexed_chunks[position]
        results.append({
            "source": chunk["source"],
            "page": chunk["page"],
            "text": chunk["text"],
            "score": float(score),
        })

    return results


if __name__ == "__main__":
    pages = load_documents()
    chunks = chunk_documents(pages)

    print(f"Loaded {len(pages)} pages")
    print(f"Created {len(chunks)} chunks")

    build_index(chunks)
    print(f"Indexed {len(indexed_chunks)} chunks after removing boilerplate")

    questions = [
        "What are the requirements for starting an LLC in Ohio?",
        "How much does it cost to file Articles of Organization in Ohio?",
        "Does a sole proprietorship need to register with the Ohio Secretary of State?",
        "What is a statutory agent for an Ohio LLC?",
    ]

    for question in questions:
        print(f"\nQuestion: {question}")
        for rank, result in enumerate(retrieve(question), start=1):
            print(
                f"\n{rank}. {result['source']}, page {result['page']} "
                f"(similarity: {result['score']:.3f})"
            )
            print(result["text"])
